          type === "byte" || type === "float" || type === "double" || 
          type === "java.lang.integer" || type === "java.lang.long" || 
          type === "java.lang.short" || type === "java.lang.byte" || 
          type === "java.lang.float" || type === "java.lang.double" || 
          type === "java.math.bigdecimal" || type === "java.math.biginteger") {
        return "NUMBER"
      }
      
      if (type === "boolean" || type === "java.lang.boolean") {
        return "BOOLEAN"
      }
      
      // 数组和集合类型
      if (type.includes("[]") || type.includes("array") || 
          type.includes("list") || type.includes("set") || 
          type.includes("collection") || type.includes("java.util.list") || 
          type.includes("java.util.set") || type.includes("java.util.collection")) {
        return "ARRAY"
      }
      
      // Map 类型
      if (type.includes("map") || type.includes("java.util.map")) {
        return "OBJECT"
      }
      
      // String 类型
      if (type === "string" || type === "java.lang.string" || type === "char" || type === "java.lang.character") {
        return "STRING"
      }
      
      // 其他类型默认为 OBJECT
      return "OBJECT"
