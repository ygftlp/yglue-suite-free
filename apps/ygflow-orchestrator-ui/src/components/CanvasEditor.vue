function normalizeEntrypoint(input?: Partial<FlowEntrypoint> | null): FlowEntrypoint | null {
  if (!input) return null
  const path = (input.path || "").trim()
  if (!path) return null
  const method = (input.method || "").trim().toUpperCase()
  return {
    path,
    method,
    replaceResponse: Boolean(input.replaceResponse),
    enabled: input.enabled !== false,
  }
}

function serializeEntrypointPayload(entrypoint: FlowEntrypoint | null) {
  if (!entrypoint) return null
  return {
    path: entrypoint.path,
    method: entrypoint.method || null,
    replaceResponse: Boolean(entrypoint.replaceResponse),
    enabled: entrypoint.enabled !== false,
  }
}

